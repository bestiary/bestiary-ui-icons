import fs from 'node:fs';
import path from 'node:path';
import { variantExportName, variantKebabName } from '../naming.js';
import type { ProcessedIcon } from '../svg-processor.js';
import type { IconVariant } from '../types.js';

const GENERATED_HEADER = '// This file is auto-generated by tools/src/cli-generate.ts. Do not edit manually.\n\n';

export function generateIconsVuePackage(icons: ProcessedIcon[], packageDir: string): void {
  const generatedDir = path.join(packageDir, 'src', 'generated');
  const iconsOutDir = path.join(generatedDir, 'icons');

  fs.rmSync(generatedDir, { recursive: true, force: true });
  fs.mkdirSync(iconsOutDir, { recursive: true });

  const indexExports: string[] = [];
  const dynamicEntries: string[] = [];

  for (const icon of icons) {
    const variants: IconVariant[] = ['outline', 'solid'];

    for (const variant of variants) {
      const exportName = variantExportName(icon.name, variant);
      const kebabName = variantKebabName(icon.name, variant);

      const fileContent =
        GENERATED_HEADER +
        `import { ${exportName} as iconNode } from '@bestiary-ui/icons/icons/${kebabName}';\n` +
        `import { createVueIcon } from '../../createVueIcon.js';\n\n` +
        `export const ${exportName} = createVueIcon(${JSON.stringify(exportName)}, iconNode);\n` +
        `export default ${exportName};\n`;

      fs.writeFileSync(path.join(iconsOutDir, `${kebabName}.ts`), fileContent, 'utf-8');

      indexExports.push(`export { ${exportName} } from './icons/${kebabName}.js';`);
      dynamicEntries.push(
        `  ${JSON.stringify(kebabName)}: () => import('./icons/${kebabName}.js').then((m) => ({ default: m.${exportName} })),`,
      );

      for (const alias of icon.meta.aliases ?? []) {
        const aliasExportName = variantExportName(alias, variant);
        const aliasKebabName = variantKebabName(alias, variant);
        indexExports.push(
          `export { ${exportName} as ${aliasExportName} } from './icons/${kebabName}.js';`,
        );
        dynamicEntries.push(
          `  ${JSON.stringify(aliasKebabName)}: () => import('./icons/${kebabName}.js').then((m) => ({ default: m.${exportName} })),`,
        );
      }
    }
  }

  fs.writeFileSync(
    path.join(generatedDir, 'index.ts'),
    GENERATED_HEADER + indexExports.join('\n') + '\n',
    'utf-8',
  );

  const dynamicContent =
    GENERATED_HEADER +
    `import type { Component } from 'vue';\n\n` +
    `export const dynamicIconImports: Record<string, () => Promise<{ default: Component }>> = {\n` +
    dynamicEntries.join('\n') +
    `\n};\n`;

  fs.writeFileSync(path.join(generatedDir, 'dynamicIconImports.ts'), dynamicContent, 'utf-8');
}
