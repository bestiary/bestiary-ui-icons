import fs from 'node:fs';
import path from 'node:path';
import { variantExportName, variantKebabName } from '../naming.js';
import type { ProcessedIcon } from '../svg-processor.js';
import type { IconVariant } from '../types.js';

const GENERATED_HEADER = '// This file is auto-generated by tools/src/cli-generate.ts. Do not edit manually.\n\n';

export function generateIconsStaticPackage(icons: ProcessedIcon[], packageDir: string): void {
  const svgOutDir = path.join(packageDir, 'icons');
  const generatedDir = path.join(packageDir, 'src', 'generated');
  const modulesOutDir = path.join(generatedDir, 'icons');

  fs.rmSync(svgOutDir, { recursive: true, force: true });
  fs.rmSync(generatedDir, { recursive: true, force: true });
  fs.mkdirSync(svgOutDir, { recursive: true });
  fs.mkdirSync(modulesOutDir, { recursive: true });

  const symbols: string[] = [];
  const indexExports: string[] = [];
  const mapImports: string[] = [];
  const mapEntries: string[] = [];

  for (const icon of icons) {
    const variants: IconVariant[] = ['outline', 'solid'];

    for (const variant of variants) {
      const data = icon[variant];
      const exportName = variantExportName(icon.name, variant);
      const kebabName = variantKebabName(icon.name, variant);

      fs.writeFileSync(path.join(svgOutDir, `${kebabName}.svg`), data.optimizedSvg + '\n', 'utf-8');
      symbols.push(`  ${data.symbolSvg}`);

      const modContent =
        GENERATED_HEADER + `export const ${exportName}: string = ${JSON.stringify(data.optimizedSvg)};\n`;
      fs.writeFileSync(path.join(modulesOutDir, `${kebabName}.ts`), modContent, 'utf-8');

      indexExports.push(`export { ${exportName} } from './icons/${kebabName}.js';`);
      mapImports.push(`import { ${exportName} } from './icons/${kebabName}.js';`);
      mapEntries.push(`  ${JSON.stringify(kebabName)}: ${exportName},`);

      for (const alias of icon.meta.aliases ?? []) {
        const aliasExportName = variantExportName(alias, variant);
        const aliasKebabName = variantKebabName(alias, variant);
        indexExports.push(
          `export { ${exportName} as ${aliasExportName} } from './icons/${kebabName}.js';`,
        );
        mapEntries.push(`  ${JSON.stringify(aliasKebabName)}: ${exportName},`);
      }
    }
  }

  const spriteContent =
    `<svg xmlns="http://www.w3.org/2000/svg" style="display: none;">\n` +
    symbols.join('\n') +
    `\n</svg>\n`;
  fs.writeFileSync(path.join(packageDir, 'sprite.svg'), spriteContent, 'utf-8');

  fs.writeFileSync(
    path.join(generatedDir, 'index.ts'),
    GENERATED_HEADER + indexExports.join('\n') + '\n',
    'utf-8',
  );

  const mapContent =
    GENERATED_HEADER +
    mapImports.join('\n') +
    `\n\nexport const icons: Record<string, string> = {\n` +
    mapEntries.join('\n') +
    `\n};\n`;
  fs.writeFileSync(path.join(generatedDir, 'icons-map.ts'), mapContent, 'utf-8');
}
